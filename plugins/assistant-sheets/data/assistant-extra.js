function рсДобавить(значения, нужно, целые, макс){
const запас = значения.map(v => макс === null || макс === undefined ? Infinity : Math.max(0, макс - v));
const база = значения.map((v, i) => Math.min(Math.max(v, 0), запас[i] === Infinity ? Math.max(v, 0) : запас[i] + Math.max(v, 0)));
const сумма = база.reduce((a, b) => a + b, 0);
if(сумма <= 0) отказ('Некому добавлять: у строк нет запаса до верхней границы.');
let доб = целые ? рсЦелымиДоли(база.map(v => v / сумма), Math.round(нужно)) : база.map(v => v / сумма * нужно);
for(let круг = 0; круг < 8; круг++){
let лишнее = 0;
доб = доб.map((x, i) => { if(x > запас[i]){ лишнее += x - запас[i]; return запас[i]; } return x; });
if(лишнее <= 1e-9) break;
const свободно = значения.map((v, i) => запас[i] - доб[i]), всего = свободно.reduce((a, b) => a + b, 0);
if(всего <= 1e-9) отказ('Некому добавлять: упёрлись в верхнюю границу, остаток ' + рсЧ(лишнее) + '.');
const ещё = целые ? рсЦелымиДоли(свободно.map(z => z / всего), Math.round(лишнее)) : свободно.map(z => z / всего * лишнее);
доб = доб.map((x, i) => x + ещё[i]);
}
return доб;
}
